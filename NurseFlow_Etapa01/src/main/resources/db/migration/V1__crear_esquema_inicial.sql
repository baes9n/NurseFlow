-- NurseFlow: modelo inicial coherente con el Caso 11.
-- Tiempos en TIMESTAMPTZ para permitir despliegue con zonas horarias diferentes.
-- Las operaciones HTTP y reglas de negocio se incorporan en etapas posteriores.

CREATE TABLE usuarios (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    correo VARCHAR(160) NOT NULL UNIQUE,
    password_hash VARCHAR(255) NOT NULL,
    rol VARCHAR(30) NOT NULL CHECK (rol IN ('ADMIN', 'ENFERMERIA')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_usuario_correo_normalizado CHECK (correo = lower(trim(correo)))
);

CREATE TABLE profesionales (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL UNIQUE REFERENCES usuarios(id),
    nombres VARCHAR(120) NOT NULL,
    apellidos VARCHAR(120) NOT NULL,
    numero_licencia VARCHAR(40) UNIQUE,
    activo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE pacientes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo VARCHAR(40) NOT NULL UNIQUE,
    nombres VARCHAR(120) NOT NULL,
    apellidos VARCHAR(120) NOT NULL,
    fecha_nacimiento DATE,
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE turnos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    area VARCHAR(80) NOT NULL,
    inicio TIMESTAMPTZ NOT NULL,
    fin TIMESTAMPTZ NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PROGRAMADO'
        CHECK (estado IN ('PROGRAMADO', 'EN_CURSO', 'CERRADO', 'CANCELADO')),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_turno_fechas CHECK (fin > inicio)
);

CREATE TABLE asignaciones_turno (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_id BIGINT NOT NULL REFERENCES turnos(id),
    profesional_id BIGINT NOT NULL REFERENCES profesionales(id),
    estado VARCHAR(30) NOT NULL DEFAULT 'ACTIVA'
        CHECK (estado IN ('ACTIVA', 'CANCELADA')),
    asignado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT uq_asignacion_profesional_turno UNIQUE (profesional_id, turno_id)
);

CREATE TABLE actividades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    asignacion_id BIGINT NOT NULL REFERENCES asignaciones_turno(id),
    paciente_id BIGINT REFERENCES pacientes(id),
    titulo VARCHAR(160) NOT NULL,
    descripcion VARCHAR(3000),
    fecha_limite TIMESTAMPTZ NOT NULL,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE'
        CHECK (estado IN ('PENDIENTE', 'EN_PROGRESO', 'COMPLETADA', 'CANCELADA')),
    completado_en TIMESTAMPTZ,
    completado_por_id BIGINT REFERENCES usuarios(id),
    creado_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    CONSTRAINT ck_actividad_completada CHECK (
        (estado = 'COMPLETADA' AND completado_en IS NOT NULL AND completado_por_id IS NOT NULL)
        OR (estado <> 'COMPLETADA' AND completado_en IS NULL AND completado_por_id IS NULL)
    )
);

CREATE TABLE procedimientos (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actividad_id BIGINT NOT NULL REFERENCES actividades(id),
    profesional_id BIGINT NOT NULL REFERENCES profesionales(id),
    detalle VARCHAR(3000) NOT NULL,
    observaciones VARCHAR(3000),
    realizado_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE novedades (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    turno_id BIGINT NOT NULL REFERENCES turnos(id),
    registrado_por_id BIGINT NOT NULL REFERENCES usuarios(id),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN ('GENERAL','INCIDENTE','CAMBIO_TURNO')),
    descripcion VARCHAR(3000) NOT NULL,
    registrada_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE auditorias (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    accion VARCHAR(70) NOT NULL,
    entidad VARCHAR(70) NOT NULL,
    registro_id BIGINT NOT NULL,
    detalle VARCHAR(3000),
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE TABLE notificaciones (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    usuario_id BIGINT NOT NULL REFERENCES usuarios(id),
    tipo VARCHAR(30) NOT NULL CHECK (tipo IN (
        'ACTIVIDAD_VENCIDA','ACTIVIDAD_PROXIMA','CAMBIO_TURNO','GENERAL')),
    mensaje VARCHAR(500) NOT NULL,
    entidad_destino VARCHAR(70),
    registro_destino_id BIGINT,
    creada_en TIMESTAMPTZ NOT NULL DEFAULT now(),
    leida_en TIMESTAMPTZ
);

CREATE INDEX idx_turnos_inicio_estado ON turnos(inicio, estado);
CREATE INDEX idx_asignaciones_profesional_estado ON asignaciones_turno(profesional_id, estado);
CREATE INDEX idx_actividades_estado_limite ON actividades(estado, fecha_limite);
CREATE INDEX idx_actividades_asignacion ON actividades(asignacion_id);
CREATE INDEX idx_procedimientos_actividad ON procedimientos(actividad_id);
CREATE INDEX idx_novedades_turno ON novedades(turno_id);
CREATE INDEX idx_auditorias_usuario_fecha ON auditorias(usuario_id, creada_en DESC);
CREATE INDEX idx_notificaciones_usuario_leida ON notificaciones(usuario_id, leida_en);
